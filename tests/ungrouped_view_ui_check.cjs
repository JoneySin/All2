// Run against a freshly started tests/group_ui_fixture.py.
const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const opt={headless:true,args:['--no-sandbox','--disable-dev-shm-usage']};
 if(process.env.CHROMIUM_PATH)opt.executablePath=process.env.CHROMIUM_PATH;
 const browser=await chromium.launch(opt),page=await browser.newPage({viewport:{width:1100,height:850}});
 const base=process.env.ALL2_UI_URL||'http://127.0.0.1:8765',errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>r.request().url().startsWith(base+'/')?r.continue():r.abort());
 await page.addInitScript(()=>localStorage.setItem('ff_dashboard_mode','tg'));
 await page.goto(base+'/dashboard');await page.locator('.grp-card').first().waitFor();
 assert.equal(await page.locator('#cddGfLabel').textContent(),'All');
 assert.deepEqual((await page.locator('#cddGfMenu .cdd-item').allTextContents()).map(t=>t.trim()),['All','Group','UnGroup']);
 assert.ok(await page.locator('#results > .grp-card').count()>0);
 assert.ok(await page.locator('#results > .file-card').count()>0);
 await page.locator('#cddGfBtn').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/search?')&&r.url().includes('gf=group')),page.locator('#cddGfMenu [data-val=group]').click()]);
 await page.locator('.grp-card').first().waitFor();
 assert.equal(await page.locator('#cddGfLabel').textContent(),'Group');
 assert.equal(await page.locator('#results > .file-card').count(),0);
 assert.equal(await page.locator('#results > .grp-card').count(),2);
 await page.locator('#cddGfBtn').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/search?')&&r.url().includes('gf=all')),page.locator('#cddGfMenu [data-val=all]').click()]);
 await page.locator('#results > .file-card').first().waitFor();
 const group=page.locator('.grp-card').filter({hasText:'Aurora Rising'}).first();
 assert.ok((await group.locator('.grp-master .poster-top .group-id-chip').textContent()).includes('#11'));
 await group.locator('.grp-title-button').click();
 assert.equal(await group.locator('.grp-variants .file-card').count(),3);
 assert.equal(await page.locator('.file-card .group-id-chip').count(),0);
 await page.locator('#cddGfBtn').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/search?')&&r.url().includes('gf=single')),page.locator('#cddGfMenu [data-val=single]').click()]);
 await page.locator('.file-card[data-fid="a1"]').first().waitFor();
 assert.equal(await page.locator('#cddGfLabel').textContent(),'UnGroup');
 assert.equal(await page.locator('.grp-card').count(),0);
 for(const fid of ['a1','a2','a3','s1','s2','f1','f2','f3'])assert.equal(await page.locator(`.file-card[data-fid="${fid}"]`).count(),1,fid);
 assert.equal(await page.locator('.file-card .group-id-chip').count(),0);
 await page.evaluate(()=>{window.__played=0;window.openInlinePlayer=()=>window.__played++;});
 await page.locator('.file-card[data-fid="a1"] .fc-name').click();assert.equal(await page.evaluate(()=>window.__played),1);
 let r=await page.request.get(base+'/api/file/editor?file_id=a1&collection=primary');assert.equal((await r.json()).group_id,'11');
 r=await page.request.post(base+'/api/group/update',{data:{group_id:'11',name:'Special Collection'}});assert.equal(r.status(),200);
 await page.evaluate(async()=>{document.querySelector('#q').value='Special Collection';await doSearch(0,true,true);});
 for(const fid of ['a1','a2','a3'])assert.equal(await page.locator(`.file-card[data-fid="${fid}"]`).count(),1,fid);
 assert.equal(await page.locator('.grp-card').count(),0);
 await page.locator('#cddGfBtn').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/search?')&&r.url().includes('gf=all')),page.locator('#cddGfMenu [data-val=all]').click()]);
 await page.locator('.grp-card').filter({hasText:'Special Collection'}).waitFor();
 await page.evaluate(async()=>{pMode='none';document.querySelector('#q').value='';await doSearch(0,true,true);});
 const textGroup=page.locator('.grp-card').filter({hasText:'Special Collection'}).first();
 assert.ok((await textGroup.locator('.grp-textinfo .group-id-chip').textContent()).includes('#11'));
 if(!await textGroup.evaluate(e=>e.classList.contains('open')))await textGroup.locator('.grp-title-button').click();
 assert.equal(await textGroup.locator('.grp-variants .file-card .group-id-chip').count(),0);
 // The administrative full scan remains available outside the filter.
 await page.setViewportSize({width:320,height:720});
 await page.locator('#selFab').click();
 const scan=page.getByRole('button',{name:'Scan all and build groups'});assert.equal(await scan.isVisible(),true);
 const bounds=await page.locator('#selBar').boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=320);
 page.once('dialog',dialog=>dialog.dismiss());await scan.click();
 await page.locator('#selBar .alt').click();
 assert.deepEqual((await page.locator('#cddGfMenu .cdd-item').allTextContents()).map(t=>t.trim()),['All','Group','UnGroup']);
 await page.evaluate(()=>{isAdminView=false;renderSelBar();});
 assert.equal(await page.locator('#selFab, #selBar').count(),0);
 assert.deepEqual((await page.locator('#cddGfMenu .cdd-item').allTextContents()).map(t=>t.trim()),['All','Group','UnGroup']);
 await page.goto(base+'/fixture/actor-cards');
 for(const mode of ['tg','none']){
   await page.evaluate(mode=>showActorCard(mode,true),mode);
   assert.equal(await page.locator('#fixture-actor .group-id-chip, #fixture-actor .actor-group-id').count(),0);
   assert.equal(await page.locator('#fixture-actor .file-card').textContent().then(t=>t.includes('GROUP #')),false);
 }
 assert.deepEqual(errors,[]);await browser.close();console.log('Ungrouped view: all files, group-name searches, playback, group-only IDs and actor cards OK');
})().catch(e=>{console.error(e);process.exit(1)});

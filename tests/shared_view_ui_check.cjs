// Run against a fresh group_ui_fixture.py; exercises real pages and shared mode.
const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const opt={headless:true,args:['--no-sandbox','--disable-dev-shm-usage']};if(process.env.CHROMIUM_PATH)opt.executablePath=process.env.CHROMIUM_PATH;
 const browser=await chromium.launch(opt),context=await browser.newContext(),page=await context.newPage(),base=process.env.ALL2_UI_URL||'http://127.0.0.1:8765',errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 let postSearches=0;page.on('request',r=>{if(r.url().includes('/api/posts/search?'))postSearches++;});
 await page.route('**/*',r=>r.request().url().startsWith(base+'/')?r.continue():r.abort());
 await page.addInitScript(()=>{window.Telegram={WebApp:{expand(){},ready(){},initData:'fixture'}};});
 await page.goto(base+'/dashboard');await page.locator('.grp-card').first().waitFor();
 assert.equal((await page.locator('#cddColLabel').innerText()).trim(),'All');
 await page.locator('#cddColBtn').click();assert.equal((await page.locator('#cddColMenu [data-val=all]').innerText()).trim(),'All');
 await page.locator('#cddModeBtn').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/search?')&&r.url().includes('mode=tg')),page.locator('#cddModeMenu [data-val=tg]').click()]);
 assert.equal(await page.evaluate(()=>localStorage.getItem('ff_view_mode')),'poster');
 await page.goto(base+'/posts');await page.locator('#post_grid_container .act-card').waitFor();
 assert.equal((await page.locator('#post_cat_lbl').innerText()).trim(),'All');
 assert.equal((await page.locator('#post_view_lbl').innerText()).trim(),'🖼️ Poster');
 assert.equal(await page.locator('#post_grid_container.grid-text-mode').count(),0);
 await page.locator('#post_cat_lbl').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/posts/search?')),page.locator('#post_cat_menu .cdd-item').filter({hasText:'Movies'}).click()]);
 await page.locator('#post_cat_lbl').click();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/posts/search?')),page.locator('#post_cat_menu .cdd-item').filter({hasText:'All'}).click()]);
 assert.equal((await page.locator('#post_cat_lbl').innerText()).trim(),'All');
 const beforeMode=postSearches;
 await page.locator('#post_view_lbl').click();await page.locator('#post_view_menu .cdd-item').filter({hasText:'Text'}).click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('ff_view_mode')),'text');
 assert.equal(postSearches,beforeMode,'post view toggle must not refetch results');
 await page.goto(base+'/actors');await page.locator('.act-text-card').waitFor();
 assert.equal((await page.locator('#dir_mode_lbl').innerText()).trim(),'📄 Text');
 await page.goto(base+'/actor/65ab12345678901234567890');
 assert.ok((await page.locator('#cddModeLabelActor').innerText()).includes('Text'));
 assert.equal((await page.locator('#cddColLabelActor').innerText()).trim(),'All');
 await page.goto(base+'/miniapp');await page.locator('#results .fc').first().waitFor();
 assert.equal(await page.locator('#results .fc .ti').count()>0,true);
 assert.equal((await page.locator('#clCol').innerText()).trim(),'All');
 await page.locator('#cbMode').click();await page.locator('#cmMode [data-val=tg]').click();
 await page.locator('#results .fc .pb').first().waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('ff_view_mode')),'poster');
 await page.goto(base+'/dashboard');await page.locator('#results .poster-box').first().waitFor();
 assert.ok((await page.locator('#cddModeLabel').innerText()).includes('Poster'));
 const other=await page.context().newPage();await other.goto(base+'/posts');
 await other.locator('#post_view_lbl').click();await other.locator('#post_view_menu .cdd-item').filter({hasText:'Text'}).click();
 await page.locator('#cddModeLabel').filter({hasText:'Text'}).waitFor();
 await page.locator('#results.mode-none').waitFor();await other.close();
 assert.deepEqual(errors,[]);await browser.close();console.log('Shared text/poster modes and All labels across dashboard, posts, profiles and miniapp OK');
})().catch(e=>{console.error(e);process.exit(1)});
